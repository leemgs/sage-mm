#!/usr/bin/env python3
"""Render ``paper/generated/observed-results.tex`` from the observed summary.

The fragment is provenance-backed and venue-neutral (compiles unchanged under
both the ACM ``acmart`` and the Elsevier ``elsarticle`` builds, like the
simulated fragment). It reports the observed proxy-harness factorial as what
it is and nothing more:

* every value is a run-level bootstrap statistic over the 3 independent runs
  per cell recorded in the observed bundle, with the fixed-seed 95% CI carried
  from ``summarize_results.py``;
* a standing banner states that this is an ARM64-Linux Python-``/proc`` proxy
  harness, NOT vendor DTV Mono/.NET6 firmware evidence, so no reader can quote
  it as an achieved deployment effect;
* GC p99 is labelled a Python ``gc`` proxy, PSS is the process-wide
  ``smaps_rollup`` share (never per-mapping ``Private_Clean`` reclaimed bytes),
  and the sub-10ms micro-run duration and n=3 are disclosed in the caption.

The file is regenerated, never hand-edited. It intentionally does NOT flip the
submission-readiness gate: n=3 micro-runs on a proxy substrate do not satisfy
the vendor-firmware measured bar in ``paper/docs/MEASURED_DEVICE_RUN_VALUES.md``.
"""
import argparse
import json
from pathlib import Path

STOCK = "G0I0R0C0"


def fmt(x, digits=2):
    return f"{x:.{digits}f}"


def ci(metric, digits=2):
    lo, hi = metric["ci95"]
    return f"[{fmt(lo, digits)}, {fmt(hi, digits)}]"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    here = Path(__file__).resolve().parents[1]
    parser.add_argument("--summary", type=Path,
                        default=here / "experiments" / "observed" / "observed_factorial_summary.json")
    parser.add_argument("--manifest", type=Path,
                        default=here / "experiments" / "observed" / "manifest_sage_mm_observed.json")
    parser.add_argument("--provenance", type=Path,
                        default=here / "experiments" / "observed" / "provenance_sage_mm_observed.csv")
    parser.add_argument("--output", type=Path,
                        default=here.parent / "paper" / "generated" / "observed-results.tex")
    args = parser.parse_args()

    summary = json.loads(args.summary.read_text(encoding="utf-8"))
    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    prov = {}
    for line in args.provenance.read_text(encoding="utf-8").splitlines()[1:]:
        if "," in line:
            key, _, value = line.partition(",")
            prov[key] = value

    groups = {g["treatment"]: g for g in summary["groups"]}
    stock = groups[STOCK]["metrics"]
    order = sorted(groups)

    lines = []
    lines.append("% AUTO-GENERATED by code/scripts/make_observed_results_tex.py")
    lines.append("% OBSERVED PROXY-HARNESS DATA -- NOT VENDOR DTV Mono/.NET6 FIRMWARE EVIDENCE.")
    lines.append(r"\subsection{Observed proxy-harness factorial (ARM64 Linux; not firmware evidence)}")
    lines.append(r"\label{sec:observed-results}")
    lines.append(
        r"\noindent\textbf{Observed, non-synthetic --- but a proxy harness, not firmware.} "
        r"The values below are actually measured (\texttt{data\_status=observed}, "
        r"\texttt{synthetic=false}), but they were collected by a Python "
        r"\texttt{resource}~$+$~\texttt{/proc/self/smaps\_rollup}~$+$~\texttt{monotonic\_ns} "
        r"harness on ARM64 Linux (kernel~" + prov.get("kernel", "?") + r"), not on a vendor "
        r"DTV Mono/.NET6 runtime. The supplied provenance is \emph{partial}: the firmware "
        r"vendor, version, and date are \texttt{unavailable} and are not fabricated here. "
        r"GC~p99 is a Python \texttt{gc.collect} proxy, not a managed-runtime pause; PSS is "
        r"the process-wide \texttt{smaps\_rollup} share, never per-mapping "
        r"\texttt{Private\_Clean} reclaimed bytes. Each cell has "
        + str(manifest.get("independent_runs_per_treatment", "?")) +
        r" independent runs (not the preregistered $\ge$30), and per-run wall time is a "
        r"sub-10\,ms micro-run. These numbers therefore validate the analysis pipeline on "
        r"real data; they are \textbf{not} an achieved memory, latency, or reliability "
        r"effect and are never quoted in the abstract or conclusion."
    )
    lines.append("")
    lines.append(r"\begin{table}[t]")
    lines.append(r"  \caption{\textbf{Observed proxy-harness factorial --- not firmware "
                 r"evidence.} Run-level means with fixed-seed ($" + str(summary["seed"]) +
                 r"$) 10{,}000-resample 95\% bootstrap CIs over $n=" +
                 str(manifest.get("independent_runs_per_treatment", "?")) +
                 r"$ independent runs per cell, on the ARM64 Linux Python proxy harness. "
                 r"Cells are the $2^4$ \textsf{GIRC} treatments (heap, interop, reclamation, "
                 r"controller). Results are directionally mixed and several metrics sit near "
                 r"the micro-run noise floor; this table exercises the pipeline and does not "
                 r"substitute for the vendor-firmware campaign of "
                 r"Section~\ref{sec:actual}.}")
    lines.append(r"  \label{tab:observed}")
    lines.append(r"  \footnotesize")
    lines.append(r"  \setlength{\tabcolsep}{4pt}")
    lines.append(r"  \begin{tabular}{@{}lrrrr@{}}")
    lines.append(r"    \toprule")
    lines.append(r"    \textbf{Cell} & \textbf{Peak PSS (MiB)} & "
                 r"\textbf{Alloc (MiB/s)} & \textbf{GC-proxy p99 (ms)} & "
                 r"\textbf{Ctrl.\ CPU (\%)} \\")
    lines.append(r"    \midrule")
    for cell in order:
        m = groups[cell]["metrics"]
        pss = m["peak_pss_mb"]
        alloc = m["allocation_rate_mb_s"]
        gc = m["gc_p99_ms"]
        cpu = m["controller_cpu_pct"]
        label = cell + (r"\,$^{\dagger}$" if cell == STOCK else "")
        lines.append(
            f"    \\textsf{{{label}}} & {fmt(pss['mean'])}~{ci(pss)} & "
            f"{fmt(alloc['mean'], 1)}~{ci(alloc, 1)} & "
            f"{fmt(gc['mean'], 3)}~{ci(gc, 3)} & "
            f"{fmt(cpu['mean'], 3)} \\\\"
        )
    lines.append(r"    \bottomrule")
    lines.append(r"  \end{tabular}\\[2pt]")
    lines.append(r"  {\footnotesize $^{\dagger}$\textsf{G0I0R0C0} is the Stock reference cell. "
                 r"Device id prefix \texttt{" + prov.get("device_id_sha256_prefix", "?") +
                 r"}; collector sha256 \texttt{" +
                 (prov.get("collector_sha256", "?")[:16]) + r"\ldots}}")
    lines.append(r"\end{table}")
    lines.append("")
    lines.append(
        r"\noindent Because the substrate is a proxy harness and $n=3$, the observed cells "
        r"do not meet the measured-result bar in the reproducibility kit's "
        r"\texttt{MEASURED\_DEVICE\_RUN\_VALUES.md} (vendor GC/EventPipe trace, per-mapping "
        r"\texttt{Private\_Clean} accounting, $\ge$30 cold-reset runs, $\ge$30\,min and 8\,h "
        r"durations). The vendor DTV Mono/.NET6 result cells accordingly remain \texttt{NA}; "
        r"this fragment is provenance-backed observed evidence for the harness alone."
    )
    lines.append("")

    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.output} ({len(order)} cells)")


if __name__ == "__main__":
    main()
